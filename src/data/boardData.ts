export function getBoardGridPosition(index: number): {
  row: number;
  col: number;
  side: 'corner' | 'bottom' | 'left' | 'top' | 'right';
} {
  if (index === 0) return { row: 11, col: 11, side: 'corner' };
  if (index > 0 && index < 10) return { row: 11, col: 11 - index, side: 'bottom' };
  if (index === 10) return { row: 11, col: 1, side: 'corner' };
  if (index > 10 && index < 20) return { row: 11 - (index - 10), col: 1, side: 'left' };
  if (index === 20) return { row: 1, col: 1, side: 'corner' };
  if (index > 20 && index < 30) return { row: 1, col: 1 + (index - 20), side: 'top' };
  if (index === 30) return { row: 1, col: 11, side: 'corner' };
  return { row: 1 + (index - 30), col: 11, side: 'right' };
}
